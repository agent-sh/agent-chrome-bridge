'use strict';

const os = require('node:os');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const HOST_NAME = 'dev.agent_chrome_bridge';
const HOST_SCRIPT = path.join(ROOT, 'bin', 'native-host.js');
const HOST_LAUNCHER = path.join(ROOT, 'bin', 'native-host-launcher.sh');

function chromeHostDir({ platform = process.platform, home = os.homedir(), env = process.env } = {}) {
  if (env.AGENT_CHROME_BRIDGE_HOST_DIR) return env.AGENT_CHROME_BRIDGE_HOST_DIR;

  if (platform === 'darwin') {
    return path.join(home, 'Library', 'Application Support', 'Google', 'Chrome', 'NativeMessagingHosts');
  }

  if (platform === 'linux') {
    return path.join(home, '.config', 'google-chrome', 'NativeMessagingHosts');
  }

  throw new Error(`Unsupported native messaging install platform: ${platform}`);
}

function chromeHostManifestPath(options) {
  return path.join(chromeHostDir(options), `${HOST_NAME}.json`);
}

function shellQuote(value) {
  return `'${String(value).replace(/'/g, "'\\''")}'`;
}

function launcherSource(nodePath = process.execPath) {
  return [
    '#!/bin/sh',
    '# Generated by scripts/install-native-host.js.',
    '# Chrome starts native hosts with a sparse PATH, so use absolute paths.',
    `exec ${shellQuote(nodePath)} ${shellQuote(HOST_SCRIPT)} "$@"`,
    '',
  ].join('\n');
}

module.exports = {
  ROOT,
  HOST_NAME,
  HOST_SCRIPT,
  HOST_LAUNCHER,
  chromeHostDir,
  chromeHostManifestPath,
  launcherSource,
};
